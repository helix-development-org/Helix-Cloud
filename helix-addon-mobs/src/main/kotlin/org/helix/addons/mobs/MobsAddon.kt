package org.helix.addons.mobs

import kotlinx.serialization.json.Json
import org.helix.addon.sdk.AddonBase
import org.helix.api.action.ActionInvocation
import org.helix.api.action.ActionResult
import org.helix.api.action.ActionSource
import org.helix.api.addon.PlayerListener
import org.helix.api.message.Messages
import org.helix.api.player.OnlinePlayer

/**
 * Network-wide mob redesign.
 *
 * The visual part lives entirely in the HXA's `pack.zip`, which the node
 * merges into the network resource pack:
 * - `assets/minecraft/textures/entity/` – restyled vanilla mob textures
 *   (same paths/layout as vanilla), visible for every player.
 * - `assets/minecraft/optifine/cem/` – cartoon Custom Entity Models (`.jem`),
 *   read by OptiFine and by Fabric's Entity Model Features. Part names,
 *   pivots and UVs stay vanilla, so vanilla animations keep working.
 *
 * The assets are generated by `tools/mobs/cem.py` (models from the CEM
 * templates) and `tools/mobs/jobs.py` (texture → model face map for the
 * Blockbench toon pass); see the module README.
 *
 * Node side, the addon only tells joining players that the new models need
 * OptiFine or Fabric + Entity Model Features (translatable `hint` message,
 * toggled via `mobs.hint`).
 */
class MobsAddon : AddonBase() {
    private val json = Json { encodeDefaults = true; ignoreUnknownKeys = true }
    private lateinit var msg: Messages
    private lateinit var config: MobsConfig

    /**
     * Loads messages and config, registers the join hint and the `mobs.*`
     * actions.
     */
    override fun enable() {
        msg = loadMessages()
        config = load()
        context.registerPlayerListener(
            /** Sends the client-mod hint on network join. */
            object : PlayerListener {
                override fun onJoin(player: OnlinePlayer) = hint(player)
            },
        )
        action(
            "mobs.hint",
            "Configures the join hint: on, off, once (first join only) or always (every join).",
            "mobs.hint <on|off|once|always>",
        ) { invocation -> configureHint(invocation.arguments.firstOrNull()?.lowercase()) }
        action("mobs.show", "Shows the mobs addon configuration.", "mobs.show") {
            ActionResult.ok(describe())
        }
    }

    private fun hint(player: OnlinePlayer) {
        if (!config.hintEnabled) return
        if (config.hintOnce) {
            val key = "hinted-" + (player.uuid ?: player.name.lowercase())
            val storage = context.storage()
            if (storage.read(key) != null) return
            storage.write(key, "true")
        }
        context.actions.invoke(
            ActionInvocation(
                "player.message",
                listOf(player.name, msg.formatFor(player.name, "hint")),
                ActionSource.ADDON,
            ),
        )
    }

    private fun configureHint(mode: String?): ActionResult {
        config = when (mode) {
            "on" -> config.copy(hintEnabled = true)
            "off" -> config.copy(hintEnabled = false)
            "once" -> config.copy(hintEnabled = true, hintOnce = true)
            "always" -> config.copy(hintEnabled = true, hintOnce = false)
            else -> return ActionResult.error("usage: mobs.hint <on|off|once|always>")
        }
        context.storage().write(STORAGE_KEY, json.encodeToString(MobsConfig.serializer(), config))
        return ActionResult.ok(describe())
    }

    private fun describe(): String =
        "join hint: " + if (!config.hintEnabled) "off" else if (config.hintOnce) "on (first join only)" else "on (every join)"

    private fun load(): MobsConfig =
        context.storage().read(STORAGE_KEY)?.let {
            runCatching { json.decodeFromString(MobsConfig.serializer(), it) }.getOrNull()
        } ?: MobsConfig()

    private companion object {
        private const val STORAGE_KEY = "mobs"
    }
}
